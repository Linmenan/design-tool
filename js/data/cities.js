/** 允许追加自定义城市（如县级市） */
export function appendCities(list){
  if (!Array.isArray(list)) return 0;
  let n = 0;
  for (const it of list){
    if (!Array.isArray(it) || it.length < 4) continue;
    RAW.push([String(it[0]), String(it[1]), +it[2], +it[3]]);
    n++;
  }
  return n;
}

/** 全局城市列表（延迟构建，方便 appendCities 追加后重建） */
export let CITIES = build();
function build(){ return RAW.map(([name, province, lng, lat]) => ({ name, province, lng, lat })); }

/** 重新构建（appendCities 之后调用） */
export function rebuildCities(){ CITIES = build(); return CITIES; }

/** 按精确名称查找（返回 {name, province, lng, lat} 或 null） */
export function findCity(name){
  if (!name) return null;
  const q = String(name).trim();
  return CITIES.find(c => c.name === q) || null;
}